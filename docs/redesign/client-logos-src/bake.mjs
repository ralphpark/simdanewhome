// Offline, reproducible logo bake. Run from the repository root with local Chrome access:
// node docs/redesign/client-logos-src/bake.mjs
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { deflateSync } from 'node:zlib';
import { dirname, resolve, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { openBrowser } from '../../../client/src/pages/site/verification/browser.mjs';

const sourceDir = dirname(fileURLToPath(import.meta.url));
const root = resolve(sourceDir, '../../..');
const outputDir = resolve(root, 'client/public/images/clients');
const verification = resolve(root, 'docs/redesign/verification/logos');
const sources = JSON.parse(await readFile(resolve(sourceDir, 'logos.json'), 'utf8'));
await mkdir(outputDir, { recursive: true });
await mkdir(verification, { recursive: true });
const browser = await openBrowser({ build: sourceDir, out: verification });
const baked = [];
try {
  for (const item of sources) {
    const original = await readFile(resolve(sourceDir, item.source));
    assert.equal(createHash('sha256').update(original).digest('hex'), item.sha256, item.source + ' original preserved');
    const mime = { '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.png': 'image/png' }[extname(item.source)];
    const input = { ...item, url: `data:${mime};base64,${original.toString('base64')}` };
    const result = await browser.ev(`(${bakeInCanvas.toString()})(${JSON.stringify(input)})`);
    assert.ok(result.pixelWidth > 0 && result.pixelHeight <= 156, item.name + ' valid output');
    await writeFile(resolve(outputDir, item.slug + '.png'), encodeMonoPng(result));
    const { alpha, ...metrics } = result;
    baked.push({ ...item, ...metrics });
  }

  const densities = baked.map(item => item.density).sort((a, b) => a - b);
  const middle = Math.floor(densities.length / 2);
  const medianDensity = densities.length % 2 ? densities[middle] : (densities[middle - 1] + densities[middle]) / 2;
  for (const item of baked) {
    // Balance optical weight in both directions; never modify the official artwork.
    item.areaFactor = Math.max(.75, Math.min(1.15, (medianDensity / item.density) ** .35));
    const area = 4800 * item.areaFactor;
    item.w = Math.round(Math.min(200, Math.sqrt(area * item.ratio)));
    item.h = Math.round(Math.max(24, Math.min(52, Math.sqrt(area / item.ratio))));
  }
  const rows = [0, 1].map(row => baked.filter(item => item.row === row));
  const rowSource = rows.map(row => '  [\n' + row.map(item => `    { name: ${JSON.stringify(item.name)}, file: "/images/clients/${item.slug}.png", w: ${item.w}, h: ${item.h} },`).join('\n') + '\n  ],').join('\n');
  const data = `// Generated by docs/redesign/client-logos-src/bake.mjs. Dimensions are optical display boxes.\nexport type ClientLogo = { name: string; file: string; w: number; h: number };\n\nexport const clientLogoRows: readonly (readonly ClientLogo[])[] = [\n${rowSource}\n];\n\n// Includes the trailing gap: both repeated groups have exactly the same width.\nexport const clientLogoTracks = clientLogoRows.map(logos => ({\n  logos,\n  duration: (logos.reduce((sum, logo) => sum + logo.w, 0) + logos.length * 68) / 40,\n  mobileDuration: (logos.reduce((sum, logo) => sum + logo.w * .6, 0) + logos.length * 32) / 40,\n}));\n`;
  await writeFile(resolve(root, 'client/src/content/clientLogos.ts'), data);
  await writeFile(resolve(verification, 'bake-report.json'), JSON.stringify({ medianDensity, area: 4800, maxHeight: 156, logos: baked }, null, 2) + '\n');

  // Inspect the baked PNGs at their real desktop size and opacity, plus a 2x crisp preview.
  const cards = await Promise.all(baked.map(async item => {
    const url = `data:image/png;base64,${(await readFile(resolve(outputDir, item.slug + '.png'))).toString('base64')}`;
    return `<article><header>${item.name}</header><div class="large"><img src="${url}" style="max-width:300px;max-height:104px"></div><div class="actual"><img src="${url}" width="${item.w}" height="${item.h}" style="object-fit:contain;opacity:${item.row ? .46 : .55}"></div><small>${item.w} × ${item.h} · density ${item.density.toFixed(2)} · area ${item.areaFactor.toFixed(2)}</small></article>`;
  }));
  const html = `<!doctype html><html lang="ko"><meta charset="utf-8"><style>*{box-sizing:border-box}body{margin:0;padding:32px;background:#f5f5f7;color:#1d1d1f;font:16px/1.5 system-ui}h1{margin:0 0 24px;font-size:26px}.grid{display:grid;grid-template-columns:repeat(4,1fr);gap:16px}article{background:white;border-radius:12px;padding:16px;height:240px}header{font-weight:600}.large{height:112px;display:flex;align-items:center;justify-content:center}.actual{height:58px;display:flex;align-items:center;justify-content:center}small{color:#6e6e73;font-size:12px}</style><h1>심다 고객사 · 단색 원본 / 실제 표시 크기</h1><div class="grid">${cards.join('')}</div></html>`;
  await writeFile(resolve(verification, 'mono-sheet.html'), html);
  await browser.viewport(1440, 32 + 63 + Math.ceil(baked.length / 4) * 256);
  await browser.ev(`document.open();document.write(${JSON.stringify(html)});document.close()`);
  await browser.ev('Promise.all([...document.images].map(image => image.decode()))');
  await browser.shot('mono-sheet');
  assert.equal(browser.report.exceptions.length, 0);
  console.log(`Baked ${baked.length} PNGs; original hashes verified; sheet: docs/redesign/verification/logos/mono-sheet.png`);
} finally {
  await browser.close();
}

async function bakeInCanvas(item) {
  const image = new Image();
  image.src = item.url;
  await image.decode();
  const canvas = document.createElement('canvas');
  const scale = 1200 / Math.max(image.naturalWidth, image.naturalHeight);
  canvas.width = Math.max(1, Math.round(image.naturalWidth * scale));
  canvas.height = Math.max(1, Math.round(image.naturalHeight * scale));
  const ctx = canvas.getContext('2d', { willReadFrequently: true });
  ctx.drawImage(image, 0, 0, canvas.width, canvas.height);
  const frame = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const pixels = frame.data;
  let left = canvas.width, right = -1, top = canvas.height, bottom = -1;
  for (let y = 0; y < canvas.height; y++) for (let x = 0; x < canvas.width; x++) {
    const i = (y * canvas.width + x) * 4;
    const coverage = item.mode === 'silhouette' ? 1 : Math.min(1, Math.max(0, (255 - Math.min(pixels[i], pixels[i + 1], pixels[i + 2])) / 40));
    pixels[i + 3] = Math.round(pixels[i + 3] * coverage);
    pixels[i] = 29; pixels[i + 1] = 29; pixels[i + 2] = 31;
    if (pixels[i + 3] > 2) { left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y); }
  }
  if (right < left) throw new Error(item.name + ': no ink');
  ctx.putImageData(frame, 0, 0);
  const inkWidth = right - left + 1, inkHeight = bottom - top + 1;
  // Leave precisely 1px of transparent padding in the final output.
  const reduction = Math.min(1, 154 / inkHeight);
  const output = document.createElement('canvas');
  output.width = Math.round(inkWidth * reduction) + 2;
  output.height = Math.round(inkHeight * reduction) + 2;
  const final = output.getContext('2d', { willReadFrequently: true });
  final.imageSmoothingEnabled = true;
  final.imageSmoothingQuality = 'high';
  final.drawImage(canvas, left, top, inkWidth, inkHeight, 1, 1, output.width - 2, output.height - 2);
  const rgba = final.getImageData(0, 0, output.width, output.height);
  let opaque = 0;
  for (let i = 0; i < rgba.data.length; i += 4) {
    if (rgba.data[i + 3] >= 128) opaque++;
    // Keep RGB exact after canvas interpolation; only alpha carries the artwork.
    rgba.data[i] = 29; rgba.data[i + 1] = 29; rgba.data[i + 2] = 31;
  }
  final.putImageData(rgba, 0, 0);
  let alpha = '';
  for (let i = 3; i < rgba.data.length; i += 4) alpha += String.fromCharCode(rgba.data[i]);
  return { alpha: btoa(alpha), pixelWidth: output.width, pixelHeight: output.height, ratio: output.width / output.height, density: opaque / ((output.width - 2) * (output.height - 2)) };
}

// Lossless indexed PNG: all 256 entries have the requested RGB; each entry has a
// different alpha. This preserves every canvas antialiasing level with smaller files.
function encodeMonoPng({ alpha, pixelWidth: width, pixelHeight: height }) {
  const pixels = Buffer.from(alpha, 'base64');
  const scanlines = Buffer.alloc((width + 1) * height);
  for (let y = 0; y < height; y++) pixels.copy(scanlines, y * (width + 1) + 1, y * width, (y + 1) * width);
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0); header.writeUInt32BE(height, 4);
  header[8] = 8; header[9] = 3;
  const palette = Buffer.alloc(768), transparency = Buffer.alloc(256);
  for (let i = 0; i < 256; i++) { palette[i * 3] = 29; palette[i * 3 + 1] = 29; palette[i * 3 + 2] = 31; transparency[i] = i; }
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]), chunk('IHDR', header), chunk('PLTE', palette), chunk('tRNS', transparency), chunk('IDAT', deflateSync(scanlines, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}

function chunk(type, data) {
  const content = Buffer.concat([Buffer.from(type), data]);
  let crc = 0xffffffff;
  for (const byte of content) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  const length = Buffer.alloc(4), checksum = Buffer.alloc(4);
  length.writeUInt32BE(data.length); checksum.writeUInt32BE((crc ^ 0xffffffff) >>> 0);
  return Buffer.concat([length, content, checksum]);
}
